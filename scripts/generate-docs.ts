/**
 * Generates docs/google-sheets-schema.md and docs/payroll-formulas.md from the schema in code, so the documentation can
 * never drift from what the setup script creates.
 *
 *   npm run docs:generate
 *   npm run docs:generate -- --check   fails when the committed docs are stale
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { buildScaledSchema, formulaColumns, inputColumns, resolveFormula, type TabDef } from '@nutex/formula-specs';
import { ROOT } from './lib/env';

const idx = buildScaledSchema(1);
const esc = (s: string) => s.replace(/\|/g, '\\|');

function schemaDoc(): string {
  const out: string[] = [
    '# Google Sheets schema', '', '> Generated by `npm run docs:generate` from `packages/formula-specs`. Do not edit by hand.', '',
    `Workbook name: **NUTEX Attendance & Payroll DB** · ${idx.tabs.length} tabs · capacities shown are the full-capacity defaults (scale with \`CAPACITY_SCALE\`).`, '',
    'Column layout rule: **input columns come first, formula columns last**. The API only ever writes the input block; formula columns are protected and pre-filled for the tab capacity.', '',
    '| # | Tab | Group | Inputs | Formulas | Capacity | Protection |', '|---|---|---|---|---|---|---|',
    ...idx.tabs.map((t, i) => `| ${i + 1} | [${t.name}](#${t.name.toLowerCase()}) | ${t.group} | ${inputColumns(t).length} | ${formulaColumns(t).length} | ${idx.rowsFor(t).toLocaleString('en-US')} | ${t.protection === 'SERVICE_ONLY' ? 'whole tab' : 'formula block'}${t.appendOnly ? ', append-only' : ''} |`), '',
  ];
  for (const t of idx.tabs) {
    out.push(`## ${t.name}`, '', t.purpose, '', `Key column: \`${t.keyColumn}\`${t.appendOnly ? ' · **append-only**' : ''}`, '', '| Column | Kind | Type | Notes |', '|---|---|---|---|');
    for (const c of t.columns) out.push(`| \`${c.name}\` | ${c.kind} | ${c.enum ? `enum ${c.enum}` : c.type}${c.ref ? ` → ${c.ref}` : ''}${c.required ? ' (required)' : ''} | ${esc(c.note ?? '')} |`);
    out.push('');
  }
  return `${out.join('\n')}\n`;
}

const CALC_TABS = ['ATTENDANCE_EVENTS', 'ATTENDANCE_DAILY', 'ATTENDANCE_ADJUSTMENTS', 'OVERTIME', 'LEAVE_APPLICATIONS', 'LEAVE_BALANCES', 'LEAVE_TRANSACTIONS', 'EMPLOYEE_SALARY', 'PAYROLL_CONTROL', 'PAYROLL_INPUTS', 'PAYROLL_CALC', 'STATUTORY_CALC', 'FULL_FINAL', 'LOANS', 'DASHBOARD_DATA'];

function formulaDoc(): string {
  const out: string[] = [
    '# Payroll, attendance and leave formulas', '', '> Generated by `npm run docs:generate`. The formulas below are the exact Google Sheets formulas the setup script writes (row 2 shown).', '',
    'All business calculations live in these formulas. TypeScript never re-computes them; it only appends raw inputs, resolves ids and moves workflow state.', '',
    '## Reading the formulas', '',
    '- Formulas use only functions available in Google Sheets **and** the local verification engine (`IF, IFERROR, INDEX, MATCH, SUMIFS, COUNTIFS, MINIFS, MAXIFS, NETWORKDAYS.INTL, PMT, ...`). No Excel-only functions.',
    '- Composite keys use `:` (for example `E003:46023`), never `|`, because `|` is treated as regex alternation by some engines.',
    '- Configuration is read from `SYSTEM_CONFIG` (`INDEX/MATCH` on the key) and effective-dated statutory values from `STATUTORY_RULES` (`SUMIFS` by rule code and effective window). Nothing is hard-coded.', '',
    '## Business rules implemented', '',
    '### Attendance',
    '1. **Work date.** An IN punch belongs to `INT(time - DAY_BOUNDARY_HOURS/24)`. A paired OUT inherits its IN work date, so night and cross-midnight shifts stay on one day.',
    '2. **Duplicates.** A punch of the same type within `DUPLICATE_WINDOW_SEC` of an earlier one is ignored.',
    '3. **Pairing.** Each OUT pairs with the latest earlier valid IN that has no OUT in between (and not older than `MAX_SEGMENT_HOURS`). Segment minutes are summed.',
    '4. **Worked minutes.** One segment: minutes minus the shift break. Several segments: the sum (break punches are trusted). An approved adjustment replaces the effective in / out; raw punches are never edited.',
    '5. **Full / half day.** `worked + grace credit >= full_day_minutes` is a full day, `>= half_day_minutes` a half day, otherwise absent. Arriving inside the grace window is not penalised.',
    '6. **Precedence.** not in service, then WFH / OD, then holiday, then weekly off, then leave, then punch-based status.',
    '7. **Credit.** Holidays, weekly offs, paid leave and WFH / OD credit a full day; unpaid leave 0; otherwise `MIN(1, worked credit + paid leave fraction)`. `lop_days = 1 - credit`.',
    '8. **Overtime.** Regular day: `worked - full_day - ot_threshold`. Holiday / weekly off: all worked minutes. Night OT is the overlap with the night window. Payroll pays `MIN(approved, calculated)`.', '',
    '### Leave',
    '1. `days_count` excludes weekly offs and holidays unless the leave type counts them (`NETWORKDAYS.INTL`).',
    '2. Balance = sum of signed ledger rows. Pending applications reduce **available**, not the ledger balance.',
    '3. `accrual_pending = MAX(0, accrual_target - accrued_so_far)`; the accrual job posts exactly that amount, once (idempotent per target).',
    '4. Carry-forward and encashable days are capped by the leave policy.', '',
    '### Payroll',
    '1. **Paid days** = sum of daily credit inside the employment window. Joiners and leavers are limited to their window and the register must contain one attendance row per in-service day.',
    '2. **Salary** is effective-dated. A revision inside the period is blended by days: `monthly = (old x days_before + new x days_from_revision) / days_in_period`, then prorated by `paid_days / days_in_period`.',
    '3. **Gross** = earned components + OT + bonus + incentive + arrears + manual adjustment. Reimbursements are added after tax.',
    '4. **PF** on the components flagged `pf_wage`, capped by the wage ceiling rule. **ESI** on `esi_wage` components, only when contract gross is within the ceiling, rounded up. **PT** by slab. **LWF** in the configured month. **TDS**: manual amount or an optional flat rate rule.',
    '5. **Net** = gross + reimbursement - (PF + ESI + PT + LWF + TDS + loan EMI + advance recovery + other deduction). `check_status` flags missing salary, missing attendance rows, unresolved exceptions and negative net.',
    '6. **Lock.** LOCKED copies `PAYROLL_CALC` to `PAYROLL_SNAPSHOT` as values with row hashes, so history is reproducible after salary or rule changes.', '',
    '> Statutory rule values in the seed data are illustrative. Verify every rule against current law and your state notifications before production use.', '',
  ];
  for (const name of CALC_TABS) {
    const t: TabDef = idx.tab(name);
    out.push(`## ${name}`, '', t.purpose, '');
    if (t.fixedRows) {
      out.push('| Metric | Formula |', '|---|---|');
      t.fixedRows.forEach((r, i) => out.push(`| \`${String(r.metric_key)}\` ${esc(String(r.label))} | \`${esc(resolveFormula(idx, t, String(r.value), i + 2))}\` |`));
      out.push('');
      continue;
    }
    for (const c of formulaColumns(t)) {
      out.push(`### ${name}.${c.name}`, '', c.note ? `${c.note}` : '', '', '```', resolveFormula(idx, t, c.formula!, 2), '```', '');
    }
  }
  return `${out.join('\n').replace(/\n{3,}/g, '\n\n')}\n`;
}

const files: Record<string, string> = { 'docs/google-sheets-schema.md': schemaDoc(), 'docs/payroll-formulas.md': formulaDoc() };
if (process.argv.includes('--check')) {
  const stale = Object.entries(files).filter(([f, c]) => !existsSync(path.join(ROOT, f)) || readFileSync(path.join(ROOT, f), 'utf8') !== c).map(([f]) => f);
  if (stale.length) { console.error(`✖ stale docs: ${stale.join(', ')}. Run npm run docs:generate`); process.exit(1); }
  console.log('✔ generated docs are up to date');
} else {
  for (const [f, c] of Object.entries(files)) { writeFileSync(path.join(ROOT, f), c, 'utf8'); console.log(`wrote ${f} (${c.length.toLocaleString()} chars)`); }
}
